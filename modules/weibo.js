function weibo_first_set(...values) {
    for (const v of values) {
        if (v != null) {
            return v;
        }
    }
    return values[values.length - 1];
}

function weibo_post_text(post) {
    const long_text = post.longText;
    if (typeof long_text === 'object' && long_text && typeof long_text.content === 'string') {
        return long_text.content;
    }
    if (typeof post.text_raw === 'string') {
        return post.text_raw;
    }
    return strip_tags(post.text || '');
}

function weibo_hashtags(post) {
    const topics = py_get(post, 'topic_struct', null);
    if (Array.isArray(topics) && topics.length) {
        return topics.map(t => t.topic_title).filter(Boolean);
    }
    const text = weibo_post_text(post);
    const matches = [...text.matchAll(/#([^#\n]+)#/g)].map(m => m[1]);
    return matches;
}

function weibo_image_urls(post) {
    const pictures = [];
    const pic_infos = py_get(post, 'pic_infos', {});
    const pic_ids = py_get(post, 'pic_ids', []);
    for (const pic_id of pic_ids) {
        if (pic_infos[pic_id]) {
            pictures.push(pic_infos[pic_id]);
        }
    }
    const mix_items = (py_get(post, 'mix_media_info', {})).items || [];
    for (const media of mix_items) {
        if (media.type === 'pic' && media.data) {
            pictures.push(media.data);
        }
    }
    const urls = [];
    for (const picture of pictures) {
        const url = weibo_first_set(
            picture.largest?.url,
            picture.original?.url,
            picture.large?.url,
            null
        );
        if (url && !urls.includes(url)) {
            urls.push(url);
        }
    }
    return urls;
}

function weibo_video_url(post) {
    const pages = [py_get(post, 'page_info')];
    const mix_items = (py_get(post, 'mix_media_info', {})).items || [];
    for (const media of mix_items) {
        if (media.type === 'video') {
            pages.push(media.data);
        }
    }
    for (const page of pages) {
        if (typeof page !== 'object' || page.object_type !== 'video') {
            continue;
        }
        const media_info = page.media_info || {};
        const url = media_info.mp4_720p_mp4 ||
            media_info.mp4_hd_url ||
            media_info.stream_url_hd ||
            media_info.stream_url;
        if (url) {
            return url;
        }
    }
    return '';
}

export function map_item(item) {
    // Verify this is a Weibo post
    if (!weibo_is_post(item)) {
        const meta = py_get(item, '__import_meta', {});
        const source = py_get(meta, 'source_url', '');
        throw new MapItemException(`Not a Weibo post (source: ${source || 'unknown'})`);
    }

    const user = item.user;
    const reposted = py_get(item, 'retweeted_status', null);
    const reposted_user = reposted && typeof reposted === 'object' ? reposted.user : null;

    // Parse created_at into a Unix timestamp (seconds)
    let unix_timestamp = null;
    if (typeof item.created_at === 'string') {
        const parsed = Date.parse(item.created_at);
        if (!isNaN(parsed)) {
            unix_timestamp = Math.floor(parsed / 1000);
        }
    }

    const meta = py_get(item, '__import_meta', {});
    const collected_from_url = readable_url(py_get(meta, 'source_platform_url', ''));

    return new MappedItem({
        collected_from_url: collected_from_url,
        id: item.idstr,
        thread_id: item.idstr,
        url: `https://weibo.com/${user.idstr}/${item.mblogid}`,
        body: weibo_post_text(item),
        body_is_shortened: weibo_is_shortened(item) ? 'yes' : 'no',
        timestamp: unix_timestamp !== null ? formatUtcTimestamp(unix_timestamp) : new MissingMappedField(''),
        unix_timestamp: unix_timestamp !== null ? unix_timestamp : new MissingMappedField(''),
        author: py_get(user, 'screen_name', ''),
        author_id: user.idstr,
        author_avatar_url: weibo_first_set(user.avatar_hd, user.profile_image_url, ''),
        author_verified: user.verified ? 'yes' : 'no',
        author_followers: value_or_missing(user, 'followers_count', ''),
        likes: value_or_missing(item, 'attitudes_count', 0),
        comments: value_or_missing(item, 'comments_count', 0),
        reposts: value_or_missing(item, 'reposts_count', 0),
        hashtags: weibo_hashtags(item).join(','),
        image_urls: weibo_image_urls(item).join(','),
        video_url: weibo_video_url(item),
        location: item.region_name ? item.region_name.replace(/^发布于/, '').trim() : new MissingMappedField(''),
        posted_with: item.source ? strip_tags(item.source) : '',
        is_promoted: item.isAd ? 'yes' : 'no',
        is_repost: reposted ? 'yes' : 'no',
        reposted_id: reposted ? py_get(reposted, 'idstr', '') : '',
        reposted_url: reposted_user && typeof reposted_user === 'object' ? `https://weibo.com/${reposted_user.idstr}/${reposted.mblogid}` : '',
        reposted_author: reposted_user && typeof reposted_user === 'object' ? py_get(reposted_user, 'screen_name', '') : '',
        reposted_body: reposted ? weibo_post_text(reposted) : '',
        reposted_body_is_shortened: reposted && weibo_is_shortened(reposted) ? 'yes' : 'no'
    });
}
