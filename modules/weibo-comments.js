/**
 * Collect comments on Weibo posts from weibo.com
 *
 * Comments load from /ajax/statuses/buildComments, on a post's own page and
 * on video pages. The first requests for a post list its top-level comments,
 * each with up to two of its replies in `comments`; opening a comment's
 * replies lists all of them. Replies are collected as items of their own.
 *
 * @param {string} response  Content of the captured response
 * @param {string} source_platform_url  URL of the page the user is on
 * @param {string} source_url  URL of the captured response
 * @returns {Array}  Weibo comments
 */
export function capture(response, source_platform_url, source_url) {
    const domain = source_platform_url.split("/")[2].toLowerCase().replace(/^www\./, '');
    if (!domain.endsWith('weibo.com')) {
        return [];
    }

    if (!response) {
        return [];
    }

    let data;
    try {
        data = JSON.parse(response);
    } catch (e) {
        return [];
    }

    if (!data || !Array.isArray(data.data)) {
        return [];
    }

    const comments = [];
    for (const comment of data.data) {
        if (!is_comment(comment)) {
            continue;
        }

        comments.push(comment);
        for (const reply of Array.isArray(comment.comments) ? comment.comments : []) {
            if (is_comment(reply)) {
                comments.push(reply);
            }
        }
    }

    return comments;
}

