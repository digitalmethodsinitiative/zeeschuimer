function weibo_commented_post(comment) {
    const extra = py_get(comment, 'analysis_extra', '');
    const fields = {};
    if (extra) {
        const parts = extra.split('|');
        for (const part of parts) {
            const idx = part.indexOf(':');
            if (idx !== -1) {
                const key = part.slice(0, idx);
                const val = part.slice(idx + 1);
                fields[key] = val;
            }
        }
    }
    return { id: fields['mid'] || null, author_id: fields['author_uid'] || null };
}

function weibo_first_set(...values) {
    for (let i = 0; i < values.length; i++) {
        const v = values[i];
        if (v !== null && v !== undefined) {
            return v;
        }
    }
    return values[values.length - 1];
}

export function map_item(item) {
    // Verify this is a Weibo comment
    if (!weibo_is_comment(item)) {
        const meta = py_get(item, '__import_meta', {});
        const src = py_get(meta, 'source_url', '');
        throw new MapItemException(`Not a Weibo comment (source: ${src || 'unknown'})`);
    }

    const user = item['user'];
    const post = weibo_commented_post(item);
    const is_reply = item['rootidstr'] !== item['idstr'];

    // Parse created_at into a Unix timestamp (seconds)
    let unix_timestamp = null;
    const created_at = py_get(item, 'created_at');
    if (typeof created_at === 'string') {
        const ms = Date.parse(created_at);
        if (!Number.isNaN(ms)) {
            unix_timestamp = Math.floor(ms / 1000);
        }
    }

    const reply_to = py_get(item, 'reply_comment') || {};

    return new MappedItem({
        collected_from_url: normalize_url_encoding(
            py_get(py_get(item, '__import_meta', {}), 'source_platform_url', '')
        ),
        id: item['idstr'],
        thread_id: post.id != null ? post.id : new MissingMappedField(''),
        post_id: post.id != null ? post.id : new MissingMappedField(''),
        post_url: post.id && post.author_id
            ? `https://weibo.com/${post.author_id}/${post.id}`
            : new MissingMappedField(''),
        author: py_get(user, 'screen_name', ''),
        author_id: user['idstr'],
        author_avatar_url: weibo_first_set(
            py_get(user, 'avatar_hd'),
            py_get(user, 'profile_image_url'),
            ''
        ),
        body: typeof py_get(item, 'text_raw') === 'string'
            ? py_get(item, 'text_raw')
            : strip_tags(py_get(item, 'text') || ''),
        timestamp: unix_timestamp != null
            ? formatUtcTimestamp(unix_timestamp)
            : new MissingMappedField(''),
        unix_timestamp: unix_timestamp != null
            ? unix_timestamp
            : new MissingMappedField(''),
        likes: weibo_first_set(
            py_get(item, 'like_counts'),
            py_get(item, 'like_count'),
            new MissingMappedField('')
        ),
        replies: is_reply ? '' : value_or_missing(item, 'total_number', ''),
        is_reply: is_reply ? 'yes' : 'no',
        root_comment_id: item['rootidstr'],
        reply_to_comment_id: weibo_first_set(py_get(reply_to, 'idstr'), ''),
        reply_to_author: weibo_first_set(
            py_get(py_get(reply_to, 'user') || {}, 'screen_name'),
            ''
        ),
        location: item['source']
            ? item['source'].replace(/^来自/, '').trimStart()
            : new MissingMappedField(''),
        is_liked_by_post_author: py_get(item, 'isLikedByMblogAuthor') ? 'yes' : 'no',
    });
}
